# Processa e adiciona sinônimos normalizados sem acentos para garantir busca insensível
processed_foods = []
for idx, food in enumerate(raw_foods, start=1):
    syn_list = [s.strip() for s in food["synonyms"].split(",") if s.strip()]
    
    # Adiciona a versão desacentuada do próprio nome e dos sinônimos
    norm_name = normalize_text(food["name"])
    syn_set = set(syn_list)
    syn_set.add(norm_name)
    
    for s in syn_list:
        norm_s = normalize_text(s)
        syn_set.add(norm_s)
        
    food["id"] = idx
    food["is_custom"] = 0
    food["synonyms"] = ",".join(sorted(syn_set))
    processed_foods.append(food)

output_path = "assets/data/taco_database.json"
with open(output_path, "w", encoding="utf-8") as f:
    json.dump(processed_foods, f, ensure_ascii=False, indent=2)

print(f"Sucesso: {len(processed_foods)} alimentos gerados com sucesso em {output_path}!")
